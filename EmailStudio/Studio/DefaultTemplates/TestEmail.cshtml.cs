using EmailStudio.Templates.Shared;

namespace EmailStudio.Templates;

/// <summary>
/// Supplies the content and default preview data for the example test email.
/// </summary>
public sealed class TestEmailModel : LayoutModel
{
    /// <summary>
    /// Gets or sets the recipient's display name used in the greeting.
    /// </summary>
    public string? Name { get; set; }

    /// <summary>
    /// Gets or sets the main message displayed in the email body.
    /// </summary>
    public string? Message { get; set; }

    /// <summary>
    /// Gets or sets the hidden preview text shown by email clients alongside the subject.
    /// </summary>
    public string? Preheader { get; set; }

    /// <summary>
    /// Creates the initial example data displayed in Email Studio's model editor.
    /// </summary>
    /// <returns>A new test email model populated with sample branding, recipient, and message values.</returns>
    public static TestEmailModel CreateDefaultModel() => new()
    {
        BrandName = "Your application",
        FooterText = "This email has been automatically generated by EmailStudio Your application",
        Name = "Alex Morgan",
        Message = "We’re glad you’re here. We’ve gathered a few useful places to help you get started.",
        Preheader = "A warm welcome and a few useful places to explore."
    };
}