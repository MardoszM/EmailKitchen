import { build } from "esbuild";
import { CSS_SUPPORT, EMAIL_CLIENTS } from "@emailens/engine";
import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const directory = path.dirname(fileURLToPath(import.meta.url));
const assets = path.resolve(directory, "../../EmailStudio/Studio/Assets");
let removedLimits = 0;
let preservedColorSchemeRules = false;
const result = await build({
    absWorkingDir: directory,
    entryPoints: ["entry.js"],
    outfile: path.join(assets, "emailens-engine.js"),
    bundle: true,
    platform: "browser",
    format: "esm",
    target: "es2022",
    minify: true,
    legalComments: "none",
    metafile: true,
    banner: {
        js: "// Emailens Engine 0.19.3 (MIT). See third-party-notices.txt for dependency licenses.\n// EmailStudio removes preview caps and preserves authored color-scheme media rules."
    },
    plugins: [
        {
            name: "local-preview-adjustments",
            setup(builder) {
                builder.onLoad(
                    { filter: /@emailens[/\\]engine[/\\]dist[/\\]chunk-.*\.js$/ },
                    async ({ path: file }) => {
                        let source = await readFile(file, "utf8");
                        for (const declaration of [
                            "var MAX_HTML_SIZE = 2 * 1024 * 1024;",
                            "var MAX_WARNING_LOCATIONS = 100;"
                        ]) {
                            if (!source.includes(declaration)) continue;
                            source = source.replace(
                                declaration,
                                declaration.replace(/= .*;/, "= Number.POSITIVE_INFINITY;")
                            );
                            removedLimits++;
                        }
                        return { contents: source, loader: "js" };
                    }
                );
                builder.onLoad({ filter: /@emailens[/\\]engine[/\\]dist[/\\]index\.js$/ }, async ({ path: file }) => {
                    const source = await readFile(file, "utf8");
                    const declaration = [
                        '          if (node.type !== "Declaration") return;',
                        "          const prop = node.property.toLowerCase();",
                        "          const border = BORDER_SHORTHAND.test(prop);"
                    ].join("\n");
                    if (source.split(declaration).length !== 2)
                        throw new Error("Expected one dark-mode CSS rule walker in the pinned Emailens engine.");

                    // Keep authored theme rules intact while simulating automatic recoloring of the base styles.
                    const preserve = [
                        '          if (node.type === "Atrule" && node.name.toLowerCase() === "media" && node.prelude &&',
                        '              /\\(\\s*prefers-color-scheme\\s*:\\s*(?:light|dark)\\s*\\)/i.test(csstree.generate(node.prelude)))',
                        "            return this.skip;",
                        declaration
                    ].join("\n");
                    preservedColorSchemeRules = true;
                    return { contents: source.replace(declaration, preserve), loader: "js" };
                });
            }
        }
    ]
});
if (removedLimits !== 2)
    throw new Error("Expected both limits in the pinned Emailens engine. Review the build before upgrading.");
if (!preservedColorSchemeRules)
    throw new Error("Expected to preserve authored color-scheme media rules in the pinned Emailens engine.");

const colorSchemeSupport = CSS_SUPPORT["@media prefers-color-scheme"];
const profiles = EMAIL_CLIENTS.map(({ id, name }) => ({
    id,
    name,
    ignoresColorScheme: colorSchemeSupport[id] === "unsupported"
}));
await writeFile(
    path.join(assets, "client-profiles.js"),
    "// Generated by tools/client-preview/build.mjs.\nexport const clientProfiles = " +
        JSON.stringify(profiles, null, 2) +
        ";\n"
);

const packages = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
    if (!input.includes("node_modules/")) continue;
    let folder = path.dirname(path.resolve(directory, input));
    while (folder.startsWith(directory)) {
        try {
            const metadata = JSON.parse(await readFile(path.join(folder, "package.json"), "utf8"));
            if (metadata.name) {
                packages.set(folder, metadata);
                break;
            }
        } catch (error) {
            if (error.code !== "ENOENT") throw error;
        }
        folder = path.dirname(folder);
    }
}
// css-tree's generated browser data includes this project's CSS definitions.
const mdn = path.join(directory, "node_modules/mdn-data");
packages.set(mdn, JSON.parse(await readFile(path.join(mdn, "package.json"), "utf8")));
const sections = [
    "Third-party software included in EmailStudio client previews.\n\nEmailens is used locally under its MIT license. No Emailens account or hosted API is used.\nThe EmailStudio build removes its HTML-size and warning-location caps and preserves authored color-scheme media rules."
];
for (const [folder, metadata] of [...packages].sort((a, b) => a[1].name.localeCompare(b[1].name))) {
    const names = (await readdir(folder)).filter((name) => /^(licen[cs]e|copying|notice)(\.|$|-)/i.test(name));
    const texts = await Promise.all(names.sort().map((name) => readFile(path.join(folder, name), "utf8")));
    if (!texts.length) {
        // boolbase 1.0.0 omits its upstream ISC license file from the npm tarball.
        texts.push(await readFile(path.join(directory, "licenses", metadata.name + ".LICENSE"), "utf8"));
    }
    sections.push(`${metadata.name}@${metadata.version} (${metadata.license})\n\n${texts.join("\n\n")}`);
}
sections.push(
    "Can I Email support data\n\n" + (await readFile(path.join(directory, "licenses/caniemail.LICENSE"), "utf8"))
);
await writeFile(path.join(assets, "third-party-notices.txt"), sections.join("\n\n" + "=".repeat(72) + "\n\n") + "\n");
console.log(`Built ${profiles.length} local client profiles with ${packages.size} third-party license notices.`);
